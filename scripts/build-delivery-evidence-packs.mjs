import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { readFile, writeFile } from 'node:fs/promises'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(resolve(root, 'packages/web/package.json'))
const { build } = require('esbuild')
const check = process.argv.includes('--check')
async function emit(path, content) {
  if (check) {
    if (!Buffer.from(await readFile(path)).equals(Buffer.from(content))) {
      throw new Error(`Generated delivery evidence is stale: ${path}`)
    }
  } else {
    await writeFile(path, content)
  }
}
const result = await build({
  entryPoints: [resolve(root, 'packages/host/src/delivery-evidence.ts')],
  // The standalone reader needs only JCS, not the A2A barrel's Hub side effects.
  alias: { '@gotong/a2a': resolve(root, 'packages/a2a/src/card-signature.ts') },
  bundle: true, platform: 'node', format: 'esm', target: 'node20', write: false,
  banner: { js: '// Generated by scripts/build-delivery-evidence-packs.mjs; edit the host source.' },
})
for (const dir of ['packs/pi/extensions/lib', 'packs/dsh/skills/gotong-envelope/scripts']) {
  await emit(resolve(root, dir, 'delivery-evidence.mjs'), result.outputFiles[0].contents)
}
await emit(resolve(root, 'packs/pi/extensions/lib/delivery-evidence.d.mts'),
  await readFile(resolve(root, 'packages/host/dist/delivery-evidence.d.ts')))
